/**
 * Input validation for everything a person can type into the VPN page.
 *
 * Rules, in the order they matter:
 *
 * 1. Nothing with a line break, NUL or other control character reaches a config
 *    file, an argv entry or a log line.
 * 2. Nothing that becomes a command-line value may start with `-` (option
 *    injection). The one exception is the arguments of a custom command, which
 *    is an opt-in feature the operator wrote themselves.
 * 3. A route target can never be, or be wide enough to behave like, the default
 *    route: IPv4 prefixes shorter than /8 and IPv6 prefixes shorter than /16 are
 *    refused, as are `0.0.0.0`, `::` and `default`.
 *
 * @module host-vpn/validate
 */
import { isIP } from 'node:net';
import { MIN_V4_PREFIX, MIN_V6_PREFIX, formatV4Net, parseV4Net } from "./cidr.js";
/** Every profile type, for validation and for the UI. */
export const PROFILE_TYPES = ['password', 'token-url', 'custom'];
/** A rejected input: HTTP 400 with a stable code and the offending field. */
export class ValidationError extends Error {
    field;
    constructor(field, message) {
        super(message);
        this.field = field;
        this.name = 'ValidationError';
    }
}
/** Longest text accepted for a name-like field. */
const MAX_TEXT = 128;
/** Most targets one profile may carry. */
export const MAX_TARGETS = 64;
/** Longest secret URL. */
const MAX_URL = 2048;
/** Longest password. */
const MAX_PASSWORD = 256;
/** C0 controls, DEL and the Unicode line/paragraph separators. */
const CONTROL = /[\u0000-\u001f\u007f\u2028\u2029]/;
/** Hostname per RFC 1123, at most 253 characters. */
const HOSTNAME = /^(?=.{1,253}$)[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)*$/i;
/** Profile ids are generated by this plugin and look like `p-1a2b3c4d`. */
export const PROFILE_ID = /^[a-z0-9][a-z0-9-]{1,40}$/;
/** Read a string field, trimmed, with control characters refused. */
function text(raw, field, options = {}) {
    if (raw === undefined || raw === null || raw === '') {
        if (options.required === true)
            throw new ValidationError(field, `${field} is required`);
        return '';
    }
    if (typeof raw !== 'string')
        throw new ValidationError(field, `${field} must be a string`);
    const value = raw.trim();
    if (CONTROL.test(raw))
        throw new ValidationError(field, `${field} contains a control character or line break`);
    if (value.length > (options.max ?? MAX_TEXT))
        throw new ValidationError(field, `${field} is longer than ${String(options.max ?? MAX_TEXT)} characters`);
    if (options.required === true && value === '')
        throw new ValidationError(field, `${field} is required`);
    if (options.noDash === true && value.startsWith('-'))
        throw new ValidationError(field, `${field} must not start with "-"`);
    return value;
}
/**
 * Validate a gateway host.
 * @param raw - hostname or IP literal.
 * @returns the host, lower-cased.
 * @throws {ValidationError} when it is not a hostname or an IP address.
 */
export function parseHost(raw, field = 'host') {
    const value = text(raw, field, { required: true, noDash: true, max: 253 }).toLowerCase();
    if (isIP(value) !== 0)
        return value;
    if (!HOSTNAME.test(value) || /^[0-9.]+$/.test(value))
        throw new ValidationError(field, `${field} is not a valid host name or IP address`);
    return value;
}
/** Validate a TCP port. */
export function parsePort(raw, field = 'port') {
    const value = typeof raw === 'string' && /^\d{1,5}$/.test(raw.trim()) ? Number(raw.trim()) : raw;
    if (typeof value !== 'number' || !Number.isInteger(value) || value < 1 || value > 65535) {
        throw new ValidationError(field, `${field} must be an integer between 1 and 65535`);
    }
    return value;
}
/**
 * Validate one route target.
 * @param raw - CIDR, single IP or host name.
 * @returns the canonical target.
 * @throws {ValidationError} for control characters, a leading `-`, anything that behaves like a default route, or an unknown shape.
 */
export function parseTarget(raw, field = 'targets') {
    const value = text(raw, field, { required: true, noDash: true, max: 260 });
    if (/\s/.test(value))
        throw new ValidationError(field, `target "${value}" must not contain spaces`);
    const lowered = value.toLowerCase();
    if (lowered === 'default' || lowered === 'localhost' || /^(0\.0\.0\.0|::)(\/0+)?$/.test(lowered)) {
        throw new ValidationError(field, `target "${value}" would replace the default route and is refused`);
    }
    const slash = value.indexOf('/');
    const addr = slash < 0 ? value : value.slice(0, slash);
    const family = isIP(addr);
    if (family === 4) {
        const net = parseV4Net(value);
        if (net === undefined)
            throw new ValidationError(field, `target "${value}" is not a valid IPv4 CIDR`);
        if (net.prefix < MIN_V4_PREFIX) {
            throw new ValidationError(field, `target "${value}" is wider than /${String(MIN_V4_PREFIX)}; a range that large behaves like the default route and is refused`);
        }
        if (net.base >>> 24 === 0)
            throw new ValidationError(field, `target "${value}" is in 0.0.0.0/8 and is refused`);
        return { kind: 'v4', value: formatV4Net(net) };
    }
    if (family === 6) {
        const lenText = slash < 0 ? '128' : value.slice(slash + 1);
        if (!/^\d{1,3}$/.test(lenText) || Number(lenText) > 128)
            throw new ValidationError(field, `target "${value}" is not a valid IPv6 CIDR`);
        if (Number(lenText) < MIN_V6_PREFIX) {
            throw new ValidationError(field, `target "${value}" is wider than /${String(MIN_V6_PREFIX)}; a range that large behaves like the default route and is refused`);
        }
        return { kind: 'v6', value: `${addr.toLowerCase()}/${lenText}` };
    }
    if (slash >= 0)
        throw new ValidationError(field, `target "${value}" is not a valid CIDR`);
    if (!HOSTNAME.test(lowered) || /^[0-9.]+$/.test(lowered))
        throw new ValidationError(field, `target "${value}" is not a valid CIDR, IP address or host name`);
    return { kind: 'host', value: lowered };
}
/** Validate a target list: non-empty, bounded, de-duplicated, order kept. */
export function parseTargets(raw) {
    const list = typeof raw === 'string' ? raw.split(/[\n,]/) : raw;
    if (!Array.isArray(list))
        throw new ValidationError('targets', 'targets must be a list');
    const seen = new Set();
    const out = [];
    for (const entry of list) {
        if (typeof entry === 'string' && entry.trim() === '')
            continue;
        const parsed = parseTarget(entry);
        if (seen.has(parsed.value))
            continue;
        seen.add(parsed.value);
        out.push(parsed.value);
    }
    if (out.length === 0)
        throw new ValidationError('targets', 'at least one target is required: without one nothing would go through the tunnel');
    if (out.length > MAX_TARGETS)
        throw new ValidationError('targets', `at most ${String(MAX_TARGETS)} targets`);
    return out;
}
/**
 * Validate a `https://host:port/path?token=…` URL.
 * @param raw - what the user pasted.
 * @returns the trimmed URL plus the gateway host and port it names.
 * @throws {ValidationError} for anything but a plain https URL without embedded credentials.
 */
export function parseSecretUrl(raw, field = 'secret') {
    const value = text(raw, field, { required: true, max: MAX_URL });
    let parsed;
    try {
        parsed = new URL(value);
    }
    catch {
        throw new ValidationError(field, 'the URL cannot be parsed');
    }
    if (parsed.protocol !== 'https:')
        throw new ValidationError(field, 'the URL must start with https://');
    if (parsed.username !== '' || parsed.password !== '')
        throw new ValidationError(field, 'the URL must not carry user:password@');
    const host = parseHost(parsed.hostname.replace(/^\[|\]$/g, ''), field);
    const port = parsed.port === '' ? 443 : parsePort(parsed.port, field);
    return { url: value, host, port };
}
/** Validate a certificate digest: 64 hex characters, colons allowed. */
function parseDigest(raw) {
    const value = text(raw, 'trustedCert', { max: 100 }).replace(/:/g, '').toLowerCase();
    if (value === '')
        return '';
    if (!/^[0-9a-f]{64}$/.test(value))
        throw new ValidationError('trustedCert', 'trustedCert must be a sha256 digest (64 hex characters)');
    return value;
}
/** Validate the argv of a custom command. */
function parseCommand(raw) {
    if (!Array.isArray(raw) || raw.length === 0)
        throw new ValidationError('command', 'command must be a non-empty list of arguments');
    if (raw.length > 32)
        throw new ValidationError('command', 'command has more than 32 arguments');
    const out = raw.map((entry, index) => text(entry, `command[${String(index)}]`, { max: 512, required: index === 0 }));
    if (!/^(\/[A-Za-z0-9._\/+-]+|[A-Za-z]:[\\\\/][^\u0000-\u001f]+)$/.test(out[0] ?? ''))
        throw new ValidationError('command[0]', 'the first argument must be an absolute path to an executable');
    return out;
}
/** Make a fresh profile id. */
export function newProfileId(random) {
    return `p-${random()}`;
}
/**
 * Validate one create/update request body.
 * @param raw - decoded JSON body.
 * @param options - `allowCustom` gates the `custom` type.
 * @returns normalised fields, the optional new secret, and the id when the caller named one.
 * @throws {ValidationError} on the first bad field.
 */
export function validateProfileInput(raw, options) {
    if (typeof raw !== 'object' || raw === null || Array.isArray(raw))
        throw new ValidationError('body', 'body must be an object');
    const body = raw;
    let id;
    if (body['id'] !== undefined && body['id'] !== '') {
        id = text(body['id'], 'id', { max: 41 });
        if (!PROFILE_ID.test(id))
            throw new ValidationError('id', 'id is not a valid profile id');
    }
    const name = text(body['name'], 'name', { required: true, max: 64 });
    const type = body['type'];
    if (type !== 'password' && type !== 'token-url' && type !== 'custom')
        throw new ValidationError('type', 'type must be "password", "token-url" or "custom"');
    if (type === 'custom' && !options.allowCustom)
        throw new ValidationError('type', 'custom commands are disabled (set allowCustomCommand: true in the plugin config)');
    const targets = parseTargets(body['targets']);
    const setDns = body['setDns'] === true;
    if (body['setDns'] !== undefined && typeof body['setDns'] !== 'boolean')
        throw new ValidationError('setDns', 'setDns must be a boolean');
    const secretRaw = body['secret'];
    if (secretRaw !== undefined && secretRaw !== null && typeof secretRaw !== 'string')
        throw new ValidationError('secret', 'secret must be a string');
    const secretText = typeof secretRaw === 'string' ? secretRaw : '';
    let host = '';
    let port = 443;
    let username = '';
    let realm = '';
    let command = [];
    let secret;
    if (type === 'password') {
        host = parseHost(body['host']);
        port = body['port'] === undefined || body['port'] === '' ? 443 : parsePort(body['port']);
        username = text(body['username'], 'username', { required: true, noDash: true });
        realm = text(body['realm'], 'realm', { max: 64 });
        if (realm !== '' && !/^[A-Za-z0-9._-]+$/.test(realm))
            throw new ValidationError('realm', 'realm may only contain letters, digits, ".", "_" and "-"');
        if (secretText !== '') {
            if (CONTROL.test(secretText))
                throw new ValidationError('secret', 'password contains a control character or line break');
            if (secretText.length > MAX_PASSWORD)
                throw new ValidationError('secret', `password is longer than ${String(MAX_PASSWORD)} characters`);
            // openfortivpn reads `password = …` from a config file and trims the value,
            // so a password with edge whitespace would silently authenticate wrongly.
            if (secretText !== secretText.trim())
                throw new ValidationError('secret', 'password must not start or end with whitespace');
            secret = secretText;
        }
    }
    else if (type === 'token-url') {
        if (secretText !== '') {
            const parsed = parseSecretUrl(secretText);
            host = parsed.host;
            port = parsed.port;
            secret = parsed.url;
        }
        else {
            // Update without a new URL: the stored gateway is kept by the caller.
            host = body['host'] === undefined || body['host'] === '' ? '' : parseHost(body['host']);
            port = body['port'] === undefined || body['port'] === '' ? 443 : parsePort(body['port']);
        }
    }
    else {
        command = parseCommand(body['command']);
        if (secretText !== '')
            secret = parseSecretUrl(secretText).url;
    }
    const trustedCert = type === 'custom' ? '' : parseDigest(body['trustedCert']);
    return { id, fields: { name, type, host, port, username, realm, trustedCert, targets, setDns, command }, secret };
}
